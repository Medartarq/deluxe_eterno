CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    username VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(255),
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    email VARCHAR(180) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    name VARCHAR(120) NOT NULL,
    phone VARCHAR(40),
    status VARCHAR(20) NOT NULL
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active BOOLEAN NOT NULL,
    description VARCHAR(1000) NOT NULL,
    image_path VARCHAR(255) NOT NULL,
    name VARCHAR(120) NOT NULL,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    catalog_key VARCHAR(40) UNIQUE,
    secondary_image_path VARCHAR(255),
    focusx INTEGER NOT NULL DEFAULT 50,
    focusy INTEGER NOT NULL DEFAULT 50,
    included_items VARCHAR(1000),
    internal_notes VARCHAR(1000),
    low_stock_threshold INTEGER NOT NULL DEFAULT 3,
    occasions VARCHAR(160),
    personalization VARCHAR(500),
    preparation_time VARCHAR(120),
    price NUMERIC(10, 2),
    price_mode VARCHAR(20),
    publication_status VARCHAR(20),
    reserved_quantity INTEGER NOT NULL DEFAULT 0,
    sku VARCHAR(40) UNIQUE,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    supply_mode VARCHAR(20),
    temporarily_unavailable BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    updated_by VARCHAR(80),
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE product_images (
    product_id BIGINT NOT NULL REFERENCES products(id),
    image_path VARCHAR(255) NOT NULL,
    image_order INTEGER NOT NULL CHECK (image_order >= 0),
    PRIMARY KEY (product_id, image_order)
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(80) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    physical_after INTEGER NOT NULL,
    physical_before INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    reason VARCHAR(255) NOT NULL,
    reserved_after INTEGER NOT NULL,
    reserved_before INTEGER NOT NULL,
    type VARCHAR(20) NOT NULL,
    product_id BIGINT NOT NULL REFERENCES products(id)
);

CREATE INDEX idx_products_category_id ON products(category_id);
CREATE INDEX idx_products_publication_status ON products(publication_status);
CREATE INDEX idx_products_supply_mode ON products(supply_mode);
CREATE INDEX idx_inquiries_status_created_at ON inquiries(status, created_at DESC);
CREATE INDEX idx_stock_movements_product_created_at ON stock_movements(product_id, created_at DESC);
