"""Migra la base Deluxe Eterno de MySQL a PostgreSQL sin modificar el origen.

Requiere:
  python -m pip install mysql-connector-python "psycopg[binary]"

Variables requeridas:
  MYSQL_PASSWORD y una de estas opciones de destino:
  - POSTGRES_PASSWORD para PostgreSQL local.
  - POSTGRES_URL para una URL completa, como la External Database URL de Render.
Opcionales:
  MYSQL_HOST (127.0.0.1), MYSQL_USER (root), MYSQL_DATABASE (deluxe_eterno)
  POSTGRES_HOST (127.0.0.1), POSTGRES_USER (postgres), POSTGRES_DATABASE (deluxe_eterno)
"""

import os
import sys

import mysql.connector
import psycopg
from psycopg import sql


MYSQL = {
    "host": os.getenv("MYSQL_HOST", "127.0.0.1"),
    "user": os.getenv("MYSQL_USER", "root"),
    "password": os.environ["MYSQL_PASSWORD"],
    "database": os.getenv("MYSQL_DATABASE", "deluxe_eterno"),
}
POSTGRES_URL = os.getenv("POSTGRES_URL")
POSTGRES = None if POSTGRES_URL else {
    "host": os.getenv("POSTGRES_HOST", "127.0.0.1"),
    "user": os.getenv("POSTGRES_USER", "postgres"),
    "password": os.environ["POSTGRES_PASSWORD"],
    "dbname": os.getenv("POSTGRES_DATABASE", "deluxe_eterno"),
}

SCHEMA = """
CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    username VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(255),
    name VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    email VARCHAR(180) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    name VARCHAR(120) NOT NULL,
    phone VARCHAR(40),
    status VARCHAR(20) NOT NULL
);
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active BOOLEAN NOT NULL,
    description VARCHAR(1000) NOT NULL,
    image_path VARCHAR(255) NOT NULL,
    name VARCHAR(120) NOT NULL,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    catalog_key VARCHAR(40) UNIQUE,
    secondary_image_path VARCHAR(255),
    focusx INTEGER NOT NULL DEFAULT 50,
    focusy INTEGER NOT NULL DEFAULT 50,
    included_items VARCHAR(1000),
    internal_notes VARCHAR(1000),
    low_stock_threshold INTEGER NOT NULL DEFAULT 3,
    occasions VARCHAR(160),
    personalization VARCHAR(500),
    preparation_time VARCHAR(120),
    price NUMERIC(10, 2),
    price_mode VARCHAR(20),
    publication_status VARCHAR(20),
    reserved_quantity INTEGER NOT NULL DEFAULT 0,
    sku VARCHAR(40) UNIQUE,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    supply_mode VARCHAR(20),
    temporarily_unavailable BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    updated_by VARCHAR(80),
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE product_images (
    product_id BIGINT NOT NULL REFERENCES products(id),
    image_path VARCHAR(255) NOT NULL,
    image_order INTEGER NOT NULL CHECK (image_order >= 0),
    PRIMARY KEY (product_id, image_order)
);
CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(80) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    physical_after INTEGER NOT NULL,
    physical_before INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    reason VARCHAR(255) NOT NULL,
    reserved_after INTEGER NOT NULL,
    reserved_before INTEGER NOT NULL,
    type VARCHAR(20) NOT NULL,
    product_id BIGINT NOT NULL REFERENCES products(id)
);
"""

TABLES = (
    "admin_users",
    "categories",
    "inquiries",
    "products",
    "product_images",
    "stock_movements",
)
BOOLEAN_COLUMNS = {
    ("admin_users", "enabled"),
    ("products", "active"),
    ("products", "temporarily_unavailable"),
}


def postgres_exists() -> bool:
    assert POSTGRES is not None
    admin = POSTGRES | {"dbname": "postgres"}
    with psycopg.connect(**admin, autocommit=True) as connection:
        with connection.cursor() as cursor:
            cursor.execute("SELECT 1 FROM pg_database WHERE datname = %s", (POSTGRES["dbname"],))
            return cursor.fetchone() is not None


def create_database() -> None:
    assert POSTGRES is not None
    admin = POSTGRES | {"dbname": "postgres"}
    with psycopg.connect(**admin, autocommit=True) as connection:
        with connection.cursor() as cursor:
            cursor.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(POSTGRES["dbname"])))


def normalize(value, is_boolean: bool):
    if isinstance(value, bytes):
        value = int.from_bytes(value, byteorder="big")
    if is_boolean:
        return bool(value)
    return value


def copy_table(source, destination, table: str) -> int:
    source.execute(f"SELECT * FROM `{table}`")
    columns = source.column_names
    rows = [
        tuple(normalize(value, (table, column) in BOOLEAN_COLUMNS) for column, value in zip(columns, row))
        for row in source.fetchall()
    ]
    if rows:
        statement = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
            sql.Identifier(table),
            sql.SQL(", ").join(map(sql.Identifier, columns)),
            sql.SQL(", ").join(sql.Placeholder() for _ in columns),
        )
        destination.executemany(statement, rows)
    return len(rows)


def reset_sequence(destination, table: str) -> None:
    destination.execute(
        sql.SQL(
            "SELECT setval(pg_get_serial_sequence({}, 'id'), "
            "COALESCE((SELECT MAX(id) FROM {}), 1), (SELECT COUNT(*) > 0 FROM {}))"
        ).format(sql.Literal(table), sql.Identifier(table), sql.Identifier(table))
    )


def destination_has_tables(connection) -> bool:
    with connection.cursor() as cursor:
        cursor.execute("""
            SELECT EXISTS (
                SELECT 1
                FROM information_schema.tables
                WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
            )
        """)
        return cursor.fetchone()[0]


def main() -> int:
    if POSTGRES_URL:
        postgres_connection = psycopg.connect(POSTGRES_URL)
        if destination_has_tables(postgres_connection):
            postgres_connection.close()
            print("La base PostgreSQL de destino ya contiene tablas; se cancela para evitar sobrescribir datos.")
            return 1
    else:
        assert POSTGRES is not None
        if postgres_exists():
            print(f"La base PostgreSQL '{POSTGRES['dbname']}' ya existe; se cancela para evitar sobrescribir datos.")
            return 1
        create_database()
        postgres_connection = psycopg.connect(**POSTGRES)

    with mysql.connector.connect(**MYSQL) as mysql_connection, postgres_connection:
        with mysql_connection.cursor() as source, postgres_connection.cursor() as destination:
            destination.execute(SCHEMA)
            counts = {table: copy_table(source, destination, table) for table in TABLES}
            for table in ("admin_users", "categories", "inquiries", "products", "stock_movements"):
                reset_sequence(destination, table)
        postgres_connection.commit()

    print("Migración finalizada:")
    for table, count in counts.items():
        print(f"  {table}: {count}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except KeyError as missing:
        print(f"Falta la variable de entorno requerida: {missing.args[0]}", file=sys.stderr)
        raise SystemExit(2)
